    /** Dot mask for a character, or null if this font has no glyph for it. */
    fun maskFor(ch: Char): Long? = GLYPHS[ch.code]

    /** True if every character in [text] can be rendered. */
    fun canRender(text: String) = text.all { GLYPHS.containsKey(it.code) }

    /** Every character the font knows, in code-point order - the set to review. */
    val CHARACTERS: List<Char> = GLYPHS.keys.sorted().map { Char(it) }

    /** [ch] as seven rows of '#' and '.', for review listings. */
    fun asRows(ch: Char): List<String> {

        val mask = maskFor(ch) ?: return emptyList()

        return (0 until Hdls1414Font.DOT_ROWS).map { row ->
            (0 until Hdls1414Font.DOT_COLUMNS)
                .map { column -> if (mask and Hdls1414Font.dotBit(row, column) != 0L) '#' else '.' }
                .joinToString("")
        }
    }
