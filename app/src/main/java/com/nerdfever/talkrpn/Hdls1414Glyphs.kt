/*
 * Which dots light for each character.
 *
 * The HDLS-1414 character set, dot for dot; details in HISTORY.md. Conventions
 * worth knowing before reading the table:
 *
 *  - Every code from 0x00 to 0x7F has a glyph. There are no gaps and no
 *    control codes: the part decodes all 128 and shows something for each.
 *  - 0x00 to 0x1F are the international bank - accented letters, currency
 *    marks and a few symbols - NOT ASCII controls. Writing 0x0A shows a glyph,
 *    it does not start a new line.
 *  - 0x20 to 0x7E are ASCII, and 0x7F is a test block of alternating dots.
 *  - LOWER CASE HAS NO DESCENDERS. There is no eighth row for one, so g p q y
 *    are drawn raised, entirely above the baseline, in short forms fitted
 *    inside the grid. That is the font, not a fault in it.
 *
 * ---------------------------------------------------------------------------
 * Bit order
 * ---------------------------------------------------------------------------
 * Each glyph is 35 bits in a Long, written here as seven five-bit binary
 * literals, TOP ROW FIRST, and within a row LEFTMOST DOT FIRST. So the literals
 * below are a picture of the character: a 1 is a lit dot and a 0 is a dark one,
 * read exactly as it sits on the page.
 *
 * The order itself is defined once, in Hdls1414Font.dotBit, and reaches this
 * file only through Hdls1414Font.packRows - imported as `dots` for the sake of
 * the table's shape. Nothing here restates it.
 *
 * ---------------------------------------------------------------------------
 * Quirks, kept
 * ---------------------------------------------------------------------------
 * These are copied rather than corrected, because the point of the table is to
 * be the part's font and not a tidier one:
 *
 *  - B and D hang their bowls one column right of their top and bottom bars,
 *    so the top-left corner stands open. Every other round capital is square.
 *  - E's middle bar is three dots wide; the accented E at 0x0E has four.
 *  - % is two open boxes either side of the slash, not the usual pair of
 *    solid 2 x 2 blocks.
 *  - The apostrophe carries a tail, so it is a raised comma rather than a
 *    plain tick.
 *
 * ---------------------------------------------------------------------------
 * Uncertain reads
 * ---------------------------------------------------------------------------
 * One character only. In 0x0E the two rows of body dots are drawn slightly
 * compressed, drifting up to half a column left of the lattice by the right-
 * hand end, so the last dot of row 2 and the last of row 4 do not sit under
 * a column. Read as full-width bars starting at column 0, which is the only
 * reading that fits the dot COUNT and matches the plain E at 0x45. Every other
 * dot in the set sits within a fifth of a pitch of its lattice point.
 */

